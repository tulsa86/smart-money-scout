import assert from 'node:assert/strict';
import {replay} from './historical-replay.mjs';
const base=Date.parse('2026-10-01T00:00:00Z');
const id='test-token';
const row=(minute,price,extras={})=>({id,time:base+minute*60000,price,liquidityUsd:200000,volume24hUsd:400000,change1hPct:8,pairCreatedAt:base-10*86400000,...extras});
const empty=replay([]);
assert.equal(empty.entries,0);
assert.equal(empty.markedEquity,100);
const profit=replay([row(0,1),row(15,1.3)]);
assert.equal(profit.entries,1);
assert.equal(profit.closedTrades,1);
assert.equal(profit.trades[0].reason,'Take profit');
assert.ok(Math.abs(profit.markedEquity-102.7413)<0.01);
const crash=replay([row(0,1),row(15,0.2)]);
assert.equal(crash.closedTrades,1);
assert.equal(crash.trades[0].reason,'Stop loss');
assert.ok(crash.trades[0].pnl < -8);
const noFuture=replay([row(0,1)]);
assert.equal(noFuture.closedTrades,0);
assert.equal(noFuture.positions.length,1);
const absent=replay([row(0,1),row(15,1.3,{id:'other',change1hPct:0})]);
assert.equal(absent.closedTrades,0);
assert.equal(absent.missingQuotes,1);
const rejected=replay([row(0,1,{liquidityUsd:50})]);
assert.equal(rejected.entries,0);
const cooldown=replay([row(0,1),row(15,1.3),row(30,1.4)]);
assert.equal(cooldown.entries,1);
const order=replay([row(15,1.3),row(0,1)]);
assert.equal(order.closedTrades,1);
console.log('PASS 8 historical replay assertions: empty, profit, crash, no future, absent quote, rejection, cooldown, unsorted history.');
